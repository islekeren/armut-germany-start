/**
 * Regenerates src/common/geo/de-postcodes.data.ts from GeoNames postcode data.
 *
 *   node scripts/build-postcode-data.mjs /path/to/zipcodes.de.json
 *
 * Input: the German file from https://github.com/zauberware/postal-codes-json-xml-csv
 * (data/DE.zip -> zipcodes.de.json), a JSON conversion of the GeoNames postal
 * code dump (https://download.geonames.org/export/zip/DE.zip), licensed
 * CC BY 4.0 by GeoNames. Several places can share a postcode, so their
 * coordinates are averaged and rounded to 3 decimals (~100 m).
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import console from "node:console";
import process from "node:process";
import { URL } from "node:url";

const input = process.argv[2];
if (!input) {
  console.error("Usage: node scripts/build-postcode-data.mjs <zipcodes.de.json>");
  process.exit(1);
}

const rows = JSON.parse(readFileSync(input, "utf8"));
const sums = new Map();
for (const row of rows) {
  const code = String(row.zipcode ?? "").trim();
  const lat = Number(row.latitude);
  const lng = Number(row.longitude);
  if (!/^\d{5}$/.test(code) || !Number.isFinite(lat) || !Number.isFinite(lng)) {
    continue;
  }
  const entry = sums.get(code) ?? { lat: 0, lng: 0, count: 0 };
  entry.lat += lat;
  entry.lng += lng;
  entry.count += 1;
  sums.set(code, entry);
}

const encoded = [...sums.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([code, { lat, lng, count }]) =>
    `${code},${(lat / count).toFixed(3)},${(lng / count).toFixed(3)}`,
  )
  .join(";");

const output = `// Generated by scripts/build-postcode-data.mjs — do not edit by hand.
// German postcode centroids from GeoNames (https://www.geonames.org/),
// licensed under CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/).
// Format: "PLZ,lat,lng" entries separated by ";" (${sums.size} postcodes).
export const DE_POSTCODE_DATA =
  "${encoded}";
`;

const target = path.resolve(
  path.dirname(new URL(import.meta.url).pathname),
  "../src/common/geo/de-postcodes.data.ts",
);
writeFileSync(target, output);
console.log(`Wrote ${sums.size} postcodes to ${target}`);
